#!/usr/bin/env python3
"""Embed the reviewed adapter/bootstrap into Umbrel's update-safe compose file.

Requires PyYAML. Run again after changing http.mjs or bootstrap.mjs.
"""
import base64
from pathlib import Path
import yaml
root = Path(__file__).resolve().parent
encoded = lambda name: base64.b64encode((root / name).read_bytes()).decode()
service = {
    'image': 'node:22.23.4-bookworm-slim@sha256:de170b39439eb0e5a3444ad7d60b015614a381e10fecae2e30ec9e735122f38d',
    'init': True,
    # Upstream api runs as root and creates private files owned by UID 0.
    'user': '0:0',
    'restart': 'on-failure',
    'depends_on': ['api'],
    'ports': ['3487:3487'],
    # Inherit the real data mount, including Umbrel custom storage overrides.
    'volumes_from': ['api:ro'],
    'environment': {
        'OPENGYM_DATA': '/data',
        'OPENGYM_UID': '',
        'MCP_TOKEN': '${APP_PASSWORD}',
        'MCP_ALLOWED_HOSTS': '${DEVICE_DOMAIN_NAME}:3487,${DEVICE_HOSTNAME}:3487,localhost:3487,127.0.0.1:3487',
        'MCP_ADAPTER_BASE64': encoded('http.mjs'),
    },
    'entrypoint': ['node', '--input-type=module', '-e'],
    'command': [f"await import('data:text/javascript;base64,{encoded('bootstrap.mjs')}')"],
    'cap_drop': ['ALL'],
    'security_opt': ['no-new-privileges:true'],
    'pids_limit': 100,
    'logging': {'driver': 'json-file', 'options': {'max-size': '5m', 'max-file': '2'}},
}
compose = root.parent / 'docker-compose.yml'
existing = compose.read_text().split('\n  # MCP HTTP sidecar')[0].rstrip()
block = yaml.safe_dump({'mcp': service}, sort_keys=False, width=120)
compose.write_text(existing + '\n\n  # MCP HTTP sidecar; generated by mcp-http/render.py.\n' + ''.join('  ' + line + '\n' for line in block.splitlines()))
